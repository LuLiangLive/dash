# 长名(>6 字)时优先裁掉的尾部通用词 —— 只裁一次, 防过度裁剪。
_TRIM_TAIL = ["灵活配置混合", "行业", "产业", "主题", "策略", "投资", "指数"]

# 误标 is_etf 的主动/固收基金 —— 不给简称。
_ACTIVE_MARKS = ("混合", "债券", "平衡", "货币")


def _strip_company(s: str) -> str:
    for c in _COMPANY:
        if s.startswith(c) and len(s) > len(c):
            return s[len(c):]
    return s


def _strip_tail(s: str) -> str:
    changed = True
    while changed:
        changed = False
        for t in _TAIL:
            if s.endswith(t) and len(s) > len(t):
                s = s[: -len(t)]
                changed = True
        s2 = s.strip(" -·")
        if s2 != s:
            s, changed = s2, True
    return s


def is_index_like(name: str) -> bool:
    """名称是否像指数/ETF 基金(不含 混合/债券 等主动标记)。"""
    n = (name or "")
    return not any(m in n for m in _ACTIVE_MARKS)


def etf_short_label(name: str) -> str:
    """从基金全称提取 ETF 简称; 返回空串表示不适合展示(主动基金误标等)。

    >>> etf_short_label("富国中证绿色电力ETF发起式联接C")
    '绿色电力'
    >>> etf_short_label("华夏科创50指数增强C")
    '科创50'
    >>> etf_short_label("摩根恒生科技ETF发起式联接(QDII)C")
    '恒生科技'
    >>> etf_short_label("易方达沪深300指数增强C")
    '沪深300'
    """
    s = (name or "").strip()
    if not s:
        return ""
    if not is_index_like(s):
        return ""
    t = _strip_tail(_strip_company(s))
    if not t:
        return ""
    # 剥交易所前缀: 剥完若剩余过短/纯数字/泛词, 则放弃剥离(保留原样,
    # 如 上证50/沪深300/中证500 这种「前缀+纯数字」宽基整体保留)。
    for p in _DROP_PREFIX:
        if t.startswith(p) and len(t) > len(p):
            rest = _strip_tail(t[len(p):])
            if len(rest) >= 2 and not rest.isdigit() and rest not in _GENERIC:
                t = rest
            break
    if not t or t in _GENERIC:
        return ""
    # 过长时裁一次尾部通用词(行业/产业/主题…), 至少保留 2 字。
    if len(t) > 6:
        for w in _TRIM_TAIL:
            if t.endswith(w) and len(t) - len(w) >= 2:
                t = t[: -len(w)]
                break
    t = _NORMALIZE.get(t, t)
    return _ALIAS.get(t, t)


