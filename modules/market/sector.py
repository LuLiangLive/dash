def infer_themes(name: str) -> list[dict]:
    """从名称推断持仓主题,带估算占比。返回 [{name, pct}]。

    优先级: 具体指数名(宽基细分) > 行业/主题词 > 板块兜底。
    单一主题时用 THEME_LEADERS 细分代表重仓股,避免笼统"XX 100%"。
    """
    hit = []
    # 1) 具体指数名(宽基细分):"沪深300/中证500/创业板/科创50..." 优先
    for theme, kws in INDEX_RULES:
        if any(kw in name for kw in kws):
            hit.append(theme)
            break
    # 2) 行业/主题词
    if not hit:
        for theme, kws in THEME_WORDS:
            if any(kw in name for kw in kws):
                hit.append(theme)
                break
    # 3) 板块兜底
    if not hit:
        sec = infer_sector(name)
        hit.append(sec if sec != "其他" else "核心资产")
    hit = list(dict.fromkeys(hit))[:3]
    # 单一主题:用细分代表股增强(如 "白酒/贵州茅台/五粮液")
    if len(hit) == 1:
        _n = hit[0]
        _leads = THEME_LEADERS.get(_n)
        if _leads:
            hit[0] = f"{_n}/{('/'.join(_leads))}"
        return [{"name": hit[0], "pct": 100.0}]
    weights = [0.6, 0.25, 0.15] if len(hit) == 3 else ([0.7, 0.3] if len(hit) == 2 else [1.0])
    return [{"name": h, "pct": round(weights[i] * 100, 1)} for i, h in enumerate(hit)]
